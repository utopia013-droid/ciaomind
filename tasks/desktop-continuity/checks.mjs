import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { parseArgs } from 'node:util';
const {values} = parseArgs({options:{source:{type:'string'}}});
assert.ok(values.source);
const source = resolve(values.source);
const state = mkdtempSync(join(tmpdir(),'ciaomind-continuity-checks-'));
const runner = fileURLToPath(new URL('./run.mjs',import.meta.url));
const badReceipt = join(state,'invalid.json');
writeFileSync(badReceipt,JSON.stringify({task_id:'wrong-task'}));
const invoke = (receipt, output) => {
  const r=spawnSync(process.execPath,[runner,'--source',source,'--receipt',receipt,'--output',output],{encoding:'utf8',timeout:15000,windowsHide:true});
  assert.equal(r.status,2);
  const result=JSON.parse(r.stdout);
  assert.equal(result.safe_diagnostic,'CONTINUITY_CHECK_FAILED');
  assert.equal(result.additional_remote_adapter_invocations,0);
  assert.equal(result.local_cli_processes,0);
};
const badOutput=join(state,'rejected.json');
invoke(badReceipt,badOutput);
assert.equal(JSON.parse(readFileSync(badOutput)).status,'blocked');
const existing=join(state,'existing.json');
writeFileSync(existing,'KEEP');
invoke(badReceipt,existing);
assert.equal(readFileSync(existing,'utf8'),'KEEP');
const forbidden=join(source,'continuity-forbidden-output.json');
assert.ok(!existsSync(forbidden));
invoke(badReceipt,forbidden);
assert.ok(!existsSync(forbidden));
console.log(JSON.stringify({checks:3,passed:3,additional_remote_adapter_invocations:0}));
